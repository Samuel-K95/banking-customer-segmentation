    "                nn.Linear(64, 32),     nn.ReLU(),",
    "                nn.Linear(32, lat_dim)",
    "            )",
    "            self.dec = nn.Sequential(",
    "                nn.Linear(lat_dim, 32), nn.ReLU(),",
    "                nn.Linear(32, 64),      nn.ReLU(),",
    "                nn.Linear(64, n_feat)",
    "            )",
    "        def forward(self, x):",
    "            z = self.enc(x)",
    "            return self.dec(z), z",
    "",
    "    def train_ae(X_np, lat_dim=16, epochs=50, batch_sz=256, lr=1e-3):",
    "        X_t    = torch.tensor(X_np, dtype=torch.float32)",
    "        model  = Autoencoder(X_np.shape[1], lat_dim)",
    "        opt    = torch.optim.Adam(model.parameters(), lr=lr)",
    "        crit   = nn.MSELoss()",
    "        loader = DataLoader(TensorDataset(X_t), batch_size=batch_sz, shuffle=True)",
    "        losses = []",
    "        for ep in range(epochs):",
    "            model.train(); ep_loss = 0",
    "            for (b,) in loader:",
    "                opt.zero_grad()",
    "                loss = crit(model(b)[0], b)",
    "                loss.backward()",
    "                opt.step()",
    "                ep_loss += loss.item()",
    "            losses.append(ep_loss / len(loader))",
    "            if (ep + 1) % 10 == 0:",
    "                print(f'  epoch {ep+1:3d}/{epochs} | loss {losses[-1]:.5f}')",
    "        model.eval()",
    "        with torch.no_grad(): _, z = model(X_t)",
    "        return z.numpy(), losses",
